import { readFile, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
import path from "node:path";
import { parseRepresentableMessages } from "../../message-projection-parser.mjs";

const SOURCE = path.resolve(import.meta.dirname, "../../../crates/recite-ui/resources/diagnostics.ftl");
const INVENTORY = path.resolve(import.meta.dirname, "../../../crates/recite-ui/resources/inventory.toml");
const OUTPUT = path.resolve(import.meta.dirname, "../src/diagnostics.generated.js");
const CONTRACT_OUTPUT = path.resolve(import.meta.dirname, "../src/diagnostic-contract.generated.js");
const DIAGNOSTIC_CONTRACT = path.resolve(import.meta.dirname,
  "../../../crates/recite-ui/resources/vscode-diagnostic-contract.tsv");

export function projectDiagnostics(source, inventory) {
  // `diagnostic_presentation_ids` is deliberately the future default-code
  // registry, not the active primary registry. Project every primary-looking
  // Fluent entry, including typed parser/PO/schema variants; selector entries
  // are retained as inventory candidates but filtered below when they cannot
  // be represented by the host's simple message projector.
  const ids = diagnosticIds(source);
  const contracts = diagnosticContracts();
  const messages = new Map();
  for (const id of ids) {
    try {
      for (const [key, value] of parseRepresentableMessages(
        source, [id], "VS Code diagnostic projection"
      )) messages.set(key, value);
    } catch (error) {
      if (!/unsupported expression/u.test(error.message)) throw error;
    }
  }
  return Object.fromEntries([...messages.entries()].map(([id, template]) => {
    const argumentsForId = contracts.get(id) ?? legacyArguments(id, template);
    const placeholders = [...template.matchAll(/\{\s*\$([a-zA-Z][a-zA-Z0-9_-]*)\s*\}/gu)]
      .map((match) => match[1]).filter((name, index, values) => values.indexOf(name) === index).sort();
    const contractNames = argumentsForId.map(({ name }) => name).sort();
    if (JSON.stringify(placeholders) !== JSON.stringify(contractNames)) {
      throw new Error(`diagnostic contract/template mismatch for ${id}`);
    }
    return [id, { template, arguments: argumentsForId.map(({ name, type }) => ({ name, type })) }];
  }));
}

export function projectDiagnosticContracts() {
  return Object.fromEntries([...diagnosticContracts().entries()].map(([id, argumentsForId]) =>
    [id, { arguments: argumentsForId }]));
}

export function renderDiagnostics(values) {
  const entries = Object.entries(values).map(([id, value]) =>
    `  ${JSON.stringify(id)}: ${JSON.stringify(value)}`
  );
  return `// Generated from crates/recite-ui/resources/diagnostics.ftl. Do not edit.\n` +
    `export default Object.freeze({\n${entries.join(",\n")}\n});\n`;
}

export function renderDiagnosticContracts(values) {
  return `// Generated by UiContract::default exporter. Do not edit.\n` +
    `export default Object.freeze(${JSON.stringify(values)});\n`;
}

export async function verifyDiagnosticProjection() {
  const expected = renderDiagnostics(projectDiagnostics(
    await readFile(SOURCE, "utf8"), await readFile(INVENTORY, "utf8")
  ));
  const actual = await readFile(OUTPUT, "utf8");
  if (actual !== expected) throw new Error("VS Code diagnostic projection is stale; run diagnostic-projections.mjs --update");
  const expectedContracts = renderDiagnosticContracts(projectDiagnosticContracts());
  const actualContracts = await readFile(CONTRACT_OUTPUT, "utf8");
  if (actualContracts !== expectedContracts) throw new Error("VS Code diagnostic contract projection is stale; run diagnostic-projections.mjs --update");
}

if (process.argv.includes("--update")) {
  await writeFile(OUTPUT, renderDiagnostics(projectDiagnostics(
    await readFile(SOURCE, "utf8"), await readFile(INVENTORY, "utf8")
  )), "utf8");
  await writeFile(CONTRACT_OUTPUT, renderDiagnosticContracts(projectDiagnosticContracts()), "utf8");
} else if (process.argv[1] === new URL(import.meta.url).pathname) {
  await verifyDiagnosticProjection();
}

function diagnosticIds(source) {
  return [...source.matchAll(/(?:^|\n)(diagnostic-[a-z0-9-]+)\s*=\s*[^\n]*/gu)]
    .map((entry) => entry[1])
    .filter((id) => !/(?:-help|-related|-meaning|-cause-\d+|-remediation-\d+)$/u.test(id));
}

function legacyArguments(id, template) {
  if (id === "diagnostic-legacy-message") return [{ name: "message", type: "string" }];
  throw new Error(`missing typed diagnostic contract for ${id}`);
}

/** Read the executable UiContract export rather than inferring types from Fluent. */
function diagnosticContracts() {
  const contracts = new Map();
  for (const line of readFileSync(DIAGNOSTIC_CONTRACT, "utf8").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [id, name = "", type = ""] = line.split("\t");
    const argumentsForId = contracts.get(id) ?? [];
    if (name) argumentsForId.push({ name, type });
    contracts.set(id, argumentsForId);
  }
  return contracts;
}
