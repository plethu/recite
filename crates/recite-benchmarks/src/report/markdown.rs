use std::fmt::{self, Write as _};

use super::{BaselineDelta, BenchReport, BenchTargetReport};

impl BenchReport {
    #[must_use]
    pub fn to_markdown(&self) -> String {
        let mut output = String::new();
        match self.write_markdown(&mut output) {
            Ok(()) => output,
            Err(error) => panic!("writing markdown to String failed: {error}"),
        }
    }

    fn write_markdown(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "# Recite Benchmark Report")?;
        writeln!(output)?;
        writeln!(output, "- Generated by: `{}`", self.generated_by)?;
        writeln!(output, "- Recite version: `{}`", self.recite_version)?;
        writeln!(output, "- Build profile: `{}`", self.build.profile)?;
        writeln!(output, "- Samples per operation: `{}`", self.sample_count)?;
        writeln!(
            output,
            "- Groups: `{}`",
            self.selected_groups
                .iter()
                .map(|group| group.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        )?;
        writeln!(output)?;
        for target in &self.targets {
            target.write_markdown(output)?;
        }
        writeln!(output, "## Caveats")?;
        writeln!(output)?;
        for caveat in &self.caveats {
            writeln!(output, "- {caveat}")?;
        }
        Ok(())
    }
}

impl BenchTargetReport {
    fn write_markdown(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "## `{}`", self.target)?;
        writeln!(output)?;
        writeln!(output, "### Project Shape")?;
        writeln!(output)?;
        writeln!(output, "| Metric | Count |")?;
        writeln!(output, "| --- | ---: |")?;
        let counts = &self.metadata.counts;
        writeln!(output, "| Source files | {} |", counts.source_files)?;
        writeln!(output, "| Schema files | {} |", counts.schema_files)?;
        writeln!(output, "| Runtime fixtures | {} |", counts.runtime_fixtures)?;
        writeln!(output, "| Locale catalogs | {} |", counts.locale_catalogs)?;
        writeln!(output, "| Recite source lines | {} |", counts.recite_lines)?;
        writeln!(output, "| Blocks | {} |", counts.blocks)?;
        writeln!(output, "| Dialogue lines | {} |", counts.dialogue_lines)?;
        writeln!(output, "| Choices | {} |", counts.choices)?;
        writeln!(output, "| Effects | {} |", counts.effects)?;
        writeln!(output, "| Conditions | {} |", counts.conditions)?;
        if let Some(words) = counts.generated_words {
            writeln!(output, "| Generated words | {words} |")?;
        }
        if let Some(bytes) = counts.project_bytes {
            writeln!(output, "| Project bytes | {bytes} |")?;
        }
        if let Some(bytes) = counts.compiled_asset_bytes {
            writeln!(output, "| Compiled asset bytes | {bytes} |")?;
        }
        writeln!(output)?;
        for note in &self.metadata.notes {
            writeln!(output, "- {note}")?;
        }
        if !self.metadata.notes.is_empty() {
            writeln!(output)?;
        }
        writeln!(output, "### Timings")?;
        writeln!(output)?;
        writeln!(
            output,
            "| Group | Operation | Median ms | Min ms | Max ms | Baseline delta |"
        )?;
        writeln!(output, "| --- | --- | ---: | ---: | ---: | ---: |")?;
        for operation in &self.operations {
            writeln!(
                output,
                "| {} | {} | {} | {} | {} | {} |",
                operation.group,
                operation.operation,
                format_ns_ms(operation.summary.median_ns),
                format_ns_ms(operation.summary.min_ns),
                format_ns_ms(operation.summary.max_ns),
                format_baseline(operation.baseline.as_ref()),
            )?;
        }
        writeln!(output)
    }
}

fn format_ns_ms(ns: u128) -> String {
    format!("{:.3}", ns as f64 / 1_000_000.0)
}

fn format_baseline(delta: Option<&BaselineDelta>) -> String {
    let Some(delta) = delta else {
        return "n/a".to_owned();
    };
    match delta.delta_percent {
        Some(percent) => format!("{percent:+.2}%"),
        None => format!("{} ns", delta.delta_ns),
    }
}
