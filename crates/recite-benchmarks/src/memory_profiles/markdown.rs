use std::fmt::{self, Write as _};

use super::MemoryProfileReport;

impl MemoryProfileReport {
    #[must_use]
    pub fn to_markdown(&self) -> String {
        let mut output = String::new();
        match self.write_markdown(&mut output) {
            Ok(()) => output,
            Err(error) => panic!("writing markdown to String failed: {error}"),
        }
    }

    fn write_markdown(&self, output: &mut String) -> fmt::Result {
        self.write_intro(output)?;
        self.write_fixture_summary(output)?;
        self.write_runtime_samples(output)?;
        write_known_limits(output)
    }

    fn write_intro(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "# Recite Memory Profiles And Known Scale Limits")?;
        writeln!(output)?;
        writeln!(output, "Generated by `memory_profile_report`.")?;
        writeln!(output)?;
        writeln!(
            output,
            "Peak compiler RSS is best-effort evidence from the local machine. {}",
            self.compiler_peak_caveat
        )?;
        writeln!(output)
    }

    fn write_fixture_summary(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "## Fixture Summary")?;
        writeln!(output)?;
        writeln!(
            output,
            "| Fixture | Sources | Dialogue lines | Choices | Effects | Conditions | Project bytes | Asset bytes | Max session bytes | LSP estimate bytes | Compiler peak RSS KiB |"
        )?;
        writeln!(
            output,
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
        )?;
        for fixture in &self.fixtures {
            writeln!(
                output,
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                fixture.fixture,
                fixture.counts.source_files,
                fixture.counts.dialogue_lines,
                fixture.counts.choices,
                fixture.counts.effects,
                fixture.counts.conditions,
                fixture.project_bytes.total,
                fixture.compiled_asset.messagepack_bytes,
                fixture.runtime_sessions.max_messagepack_bytes,
                fixture.lsp_index.estimated_summary_bytes,
                optional_u64(fixture.compiler_peak_rss_kib),
            )?;
        }
        writeln!(output)
    }

    fn write_runtime_samples(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "## Runtime Session Samples")?;
        writeln!(output)?;
        for fixture in &self.fixtures {
            writeln!(output, "### `{}`", fixture.fixture)?;
            writeln!(output)?;
            writeln!(output, "| Sample | MessagePack bytes |")?;
            writeln!(output, "| --- | ---: |")?;
            for sample in &fixture.runtime_sessions.samples {
                writeln!(output, "| {} | {} |", sample.name, sample.messagepack_bytes)?;
            }
            writeln!(output)?;
        }
        Ok(())
    }
}

fn write_known_limits(output: &mut String) -> fmt::Result {
    writeln!(output, "## Known Limits")?;
    writeln!(output)?;
    writeln!(
        output,
        "- Numeric budgets remain evidence, not release contracts, until [#109 Perf: establish release benchmark baseline profile](https://github.com/plethu/recite/issues/109) establishes the release baseline."
    )?;
    writeln!(
        output,
        "- Peak RSS depends on allocator, operating system, build profile, and measurement environment."
    )?;
    writeln!(
        output,
        "- Generated `medium`, `large`, and `epic` fixtures are produced on demand under `target/recite-benchmarks/generated` and are not checked in."
    )?;
    writeln!(
        output,
        "- LSP memory is an estimated index-summary size, not a retained-heap profiler result."
    )?;
    writeln!(
        output,
        "- Adapter import refresh, watch latency, allocation counts, and clone-pressure limits remain owned by their dedicated performance follow-up issues."
    )
}

fn optional_u64(value: Option<u64>) -> String {
    value
        .map(|value| value.to_string())
        .unwrap_or_else(|| "n/a".to_owned())
}
