use std::fmt::{self, Write as _};

use super::{RuntimeAllocationReport, RuntimeAllocationStats};

impl RuntimeAllocationReport {
    #[must_use]
    pub fn to_markdown(&self) -> String {
        let mut output = String::new();
        match self.write_markdown(&mut output) {
            Ok(()) => output,
            Err(error) => panic!("writing markdown to String failed: {error}"),
        }
    }

    fn write_markdown(&self, output: &mut String) -> fmt::Result {
        self.write_intro(output)?;
        self.write_operations(output)?;
        self.write_caveats(output)
    }

    fn write_intro(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "# Recite Runtime Allocation Pressure")?;
        writeln!(output)?;
        writeln!(output, "Generated by `{}`.", self.generated_by)?;
        writeln!(output)?;
        writeln!(
            output,
            "Allocation counts are local measurement evidence, not release gates."
        )?;
        writeln!(output)
    }

    fn write_operations(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "## Operations")?;
        writeln!(output)?;
        for fixture in &self.fixtures {
            writeln!(output, "### `{}`", fixture.fixture)?;
            writeln!(output)?;
            writeln!(
                output,
                "| Operation | Allocations | Allocated bytes | Reallocations | Reallocated bytes | Deallocations | Deallocated bytes |"
            )?;
            writeln!(output, "| --- | ---: | ---: | ---: | ---: | ---: | ---: |")?;
            for operation in &fixture.operations {
                write_stats_row(output, operation.operation, &operation.stats)?;
            }
            writeln!(output)?;
        }
        Ok(())
    }

    fn write_caveats(&self, output: &mut String) -> fmt::Result {
        writeln!(output, "## Caveats")?;
        writeln!(output)?;
        for caveat in &self.caveats {
            writeln!(output, "- {caveat}")?;
        }
        Ok(())
    }
}

fn write_stats_row(
    output: &mut String,
    operation: &str,
    stats: &RuntimeAllocationStats,
) -> fmt::Result {
    writeln!(
        output,
        "| {operation} | {} | {} | {} | {} | {} | {} |",
        stats.allocations,
        stats.bytes_allocated,
        stats.reallocations,
        stats.bytes_reallocated,
        stats.deallocations,
        stats.bytes_deallocated,
    )
}
